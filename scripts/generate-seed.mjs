// Writes supabase/seed.sql from the demo-store fixtures, so the local
// database, the unit tests and the mock images all share one source.
// Run: npm run db:seed   (then `npm run db:reset` to load it)
//
// Node loads the .ts modules directly (built-in TypeScript type stripping).
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mockDb } from '../src/mocks/index.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase', 'seed.sql');

/** Templates the demo stores use. The template itself lives in code. */
const TEMPLATES = [{ key: 'silk', name: 'Silk' }];

/** The demo stores' plan: Growth (20261123130000_create_store.sql). */
const PLAN_ID = '00000000-0000-4000-8000-000000000002';
const SUBSCRIPTIONS = mockDb.tenants.map((tenant) => ({
  tenant_id: tenant.id,
  plan_id: PLAN_ID,
}));

/** Insert order respects foreign keys. */
const TABLES = [
  ['templates', TEMPLATES],
  ['tenants', mockDb.tenants],
  ['subscriptions', SUBSCRIPTIONS],
  ['tenant_domains', mockDb.tenant_domains],
  ['tenant_themes', mockDb.tenant_themes],
  ['categories', mockDb.categories],
  ['banners', mockDb.banners],
  ['store_pages', mockDb.store_pages],
  ['products', mockDb.products],
  ['product_categories', mockDb.product_categories],
  ['product_variants', mockDb.product_variants],
  ['product_images', mockDb.product_images],
];

function literal(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Bad number: ${value}`);
    return String(value);
  }
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`;
  return `${literal(JSON.stringify(value))}::jsonb`;
}

function insert(table, rows) {
  if (rows.length === 0) return '';
  const columns = Object.keys(rows[0]);
  for (const row of rows) {
    const keys = Object.keys(row);
    if (
      keys.length !== columns.length ||
      keys.some((k, i) => k !== columns[i])
    ) {
      throw new Error(`${table}: rows have different columns`);
    }
  }
  const values = rows
    .map((row) => `  (${columns.map((c) => literal(row[c])).join(', ')})`)
    .join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${values};\n`;
}

const sql = [
  '-- GENERATED by scripts/generate-seed.mjs from src/mocks/fixtures.ts.',
  '-- Do not edit by hand: change the fixtures and run `npm run db:seed`.',
  '-- Loaded by `npm run db:reset` (local only). Two demo stores:',
  '-- saree-demo.localhost and boutique-demo.localhost.',
  '',
  ...TABLES.map(([table, rows]) => insert(table, rows)),
].join('\n');

await writeFile(OUT, sql);
const total = TABLES.reduce((n, [, rows]) => n + rows.length, 0);
console.log(
  `Wrote ${total} rows in ${TABLES.length} tables to supabase/seed.sql`,
);
